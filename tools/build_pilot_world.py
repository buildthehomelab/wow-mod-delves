#!/usr/bin/env python3
"""Render a collision-guarded isolated-test world package. No DB connections."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / 'test-package/earthcrawl.json'


def render():
    source = SPEC.read_bytes()
    p = json.loads(source)
    digest = hashlib.sha256(source).hexdigest()
    boss, brann = p['boss_entry'], p['brann_entry']
    objective, potion = p['objective_entry'], p['potion_entry']
    map_id, area = p['map'], p['area']
    spawn = p['boss_spawn']
    guids = ','.join(map(str, p['objective_spawns']))
    coordinates = p['objective_xyz']
    if len(coordinates) != len(p['objective_spawns']) or len(coordinates) != 4:
        raise ValueError('Expected four test markers')
    if len(set(p['objective_spawns'])) != 4:
        raise ValueError('Repeated object GUID')
    name = p['package']
    if name != 'earthcrawl-combat-pilot-v1':
        raise ValueError('Unknown package identity')
    marker = f"package = '{name}' AND manifest_sha256 = '{digest}'"
    header = '-- Generated by tools/build_pilot_world.py. Isolated-test database only.\n'
    schema = '''CREATE TABLE IF NOT EXISTS mod_delves_world_package (
    package VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    manifest_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL
) ENGINE=InnoDB;
'''
    start = '''DELIMITER //
CREATE PROCEDURE evermore_delve_install_v1()
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    IF RIGHT(DATABASE(), 11) <> '_delve_test' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Use a dedicated database ending in _delve_test';
    END IF;
''' + schema + '''    START TRANSACTION;
'''
    engine_guard = '''    IF (SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE()
        AND table_name IN ('instance_template','creature','creature_template','creature_template_model',
            'gameobject','gameobject_template','gameobject_template_addon','mod_delves_world_package')
        AND engine = 'InnoDB') <> 8 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Delve pilot requires complete InnoDB world tables';
    END IF;
'''
    guard = engine_guard + f'''    IF EXISTS (SELECT 1 FROM mod_delves_world_package WHERE package = '{name}')
        OR EXISTS (SELECT 1 FROM instance_template WHERE map = {map_id})
        OR EXISTS (SELECT 1 FROM creature WHERE map = {map_id} OR guid = {spawn} OR id1 IN ({boss},{brann}) OR id2 IN ({boss},{brann}) OR id3 IN ({boss},{brann}))
        OR EXISTS (SELECT 1 FROM gameobject WHERE map = {map_id} OR guid IN ({guids}) OR id IN ({objective},{potion}))
        OR EXISTS (SELECT 1 FROM creature_template WHERE entry IN ({boss},{brann}))
        OR EXISTS (SELECT 1 FROM creature_template_model WHERE CreatureID IN ({boss},{brann}))
        OR EXISTS (SELECT 1 FROM gameobject_template WHERE entry IN ({objective},{potion}))
        OR EXISTS (SELECT 1 FROM gameobject_template_addon WHERE entry IN ({objective},{potion})) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Delve pilot collision or already installed; no content replaced';
    END IF;
'''
    writes = f'''    INSERT INTO instance_template (map,parent,script,allowMount) VALUES ({map_id},0,'instance_evermore_delves',0);
    INSERT INTO creature_template
        (entry,name,subname,minlevel,maxlevel,faction,rank,unit_class,type,BaseAttackTime,RangeAttackTime,HealthModifier,ManaModifier,DamageModifier,ExperienceModifier,ScriptName)
        VALUES ({boss},'Ab''enar','Earthcrawl combat test',30,30,14,1,2,7,2000,2000,8,5,1.2,0,'boss_evermore_abenar'),
               ({brann},'Brann Bronzebeard','Delve companion test',30,30,35,0,1,7,2000,2000,20,1,0,0,'npc_evermore_delve_brann');
    INSERT INTO creature_template_model (CreatureID,Idx,CreatureDisplayID,DisplayScale,Probability,VerifiedBuild)
        VALUES ({boss},0,{p['boss_display']},0.35,1,0), ({brann},0,{p['brann_display']},1,1,0);
    INSERT INTO gameobject_template (entry,type,displayId,name,Data3,ScriptName,VerifiedBuild)
        VALUES ({objective},10,{p['objective_display']},'Earthcrawl rescue test marker',3000,'go_evermore_delve_objective',0),
               ({potion},5,{p['potion_display']},'Personal healing potion',0,'go_evermore_delve_potion',0);
    INSERT INTO gameobject_template_addon (entry,faction,flags) VALUES ({objective},0,0),({potion},0,0);
    INSERT INTO creature (guid,id1,map,zoneId,areaId,spawnMask,phaseMask,position_x,position_y,position_z,orientation,spawntimesecs,Comment)
        VALUES ({spawn},{boss},{map_id},{area},{area},1,1,{p['boss_xyz'][0]},{p['boss_xyz'][1]},{p['boss_xyz'][2]},0,86400,'{name}');
    INSERT INTO gameobject (guid,id,map,zoneId,areaId,spawnMask,phaseMask,position_x,position_y,position_z,orientation,rotation3,spawntimesecs,animprogress,state,Comment) VALUES
'''
    rows = []
    for guid, xyz in zip(p['objective_spawns'], coordinates):
        rows.append(f"        ({guid},{objective},{map_id},{area},{area},1,1,{xyz[0]},{xyz[1]},{xyz[2]},0,1,300,100,1,'{name}')")
    writes += ',\n'.join(rows) + ';\n'
    writes += f"    INSERT INTO mod_delves_world_package (package,manifest_sha256) VALUES ('{name}','{digest}');\n"
    end = '''    COMMIT;
END//
DELIMITER ;
CALL evermore_delve_install_v1();
DROP PROCEDURE evermore_delve_install_v1;
'''
    install = header + start + guard + writes + end
    rollback = header + '''DELIMITER //
CREATE PROCEDURE evermore_delve_rollback_v1()
BEGIN
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    IF RIGHT(DATABASE(), 11) <> '_delve_test' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Use a dedicated database ending in _delve_test';
    END IF;
    START TRANSACTION;
''' + engine_guard + f'''    IF NOT EXISTS (SELECT 1 FROM mod_delves_world_package WHERE {marker}) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Missing matching delve package receipt; rollback refused';
    END IF;
    DELETE FROM gameobject WHERE id = {objective} AND guid IN ({guids}) AND map = {map_id} AND Comment = '{name}';
    DELETE FROM creature WHERE id1 = {boss} AND guid = {spawn} AND map = {map_id} AND Comment = '{name}';
    IF EXISTS (SELECT 1 FROM creature WHERE id1 IN ({boss},{brann}) OR id2 IN ({boss},{brann}) OR id3 IN ({boss},{brann}))
        OR EXISTS (SELECT 1 FROM gameobject WHERE id IN ({objective},{potion})) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Unexpected delve actors; rollback refused';
    END IF;
    DELETE FROM gameobject_template_addon WHERE entry IN ({objective},{potion});
    DELETE FROM gameobject_template WHERE entry IN ({objective},{potion});
    DELETE FROM creature_template_model WHERE CreatureID IN ({boss},{brann});
    DELETE FROM creature_template WHERE entry IN ({boss},{brann});
    DELETE FROM instance_template WHERE map = {map_id} AND script = 'instance_evermore_delves';
    DELETE FROM mod_delves_world_package WHERE {marker};
    COMMIT;
END//
DELIMITER ;
CALL evermore_delve_rollback_v1();
DROP PROCEDURE evermore_delve_rollback_v1;
'''
    return install, rollback


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.output.exists():
        parser.error('Output must be a new directory')
    install, rollback = render()
    args.output.mkdir(parents=True)
    (args.output / 'world.install.sql').write_text(install)
    (args.output / 'world.rollback.sql').write_text(rollback)


if __name__ == '__main__':
    main()
